"""Colour themes for Pechi. Earth tones first, each one a soft blanket for the pup."""

from textual.theme import Theme


def theme(
    name: str,
    dark: bool,
    ground: str,
    card: str,
    band: str,
    ink: str,
    muted: str,
    main: str,
    accent: str,
    good: str,
    bad: str,
) -> Theme:
    return Theme(
        name=name,
        dark=dark,
        background=ground,
        surface=card,
        panel=band,
        foreground=ink,
        primary=main,
        secondary=main,
        accent=accent,
        success=good,
        warning=accent,
        error=bad,
        variables={
            "pechi-muted": muted,
            "input-selection-background": f"{accent} 35%",
            "block-cursor-background": main,
            "block-cursor-foreground": ground,
            "footer-background": band,
        },
    )


